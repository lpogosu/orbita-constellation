/**
 * Кегль мелкого текста на ужатом полотне.
 *
 * Полотно 1920×1080 целиком масштабируется под окно, и вместе с блоками мельчает текст:
 * на 1366×768 (коэффициент 0.71) подпись макета 12px выходит на экран в 8.5px. Раскладка
 * хранит пропорции Figma, поэтому блоки ужимаются как прежде, а кегль компенсируется: у
 * каждого размера есть нижняя граница кегля на экране, ниже которой текст не мельчает,
 * пока хватает запаса роста.
 *
 * Модуль без DOM: его читает и `tailwind.config.ts`, и код, который рисует текст сам
 * (графики и карта).
 */

/**
 * Во сколько раз текст может вырасти относительно макета. Предел нужен тесным местам:
 * колонкам таблиц, чипам, строкам фиксированной высоты. 1.5 покрывает ноутбучные окна до
 * 1280×720 включительно; в ещё меньшем окне рост упирается в предел, и до порога потока
 * текст снова мельчает вместе с полотном.
 */
export const MAX_TEXT_GROWTH = 1.5;

/**
 * Нижняя граница кегля на экране для текста макетного размера `px`.
 *
 * Подписи и капс-заголовки держатся на 10px, основной текст 13–15px — на 11–12px. Крупнее
 * граница не растёт: такой текст на ноутбуке читается и так, а рост крупного текста
 * сдвигал бы вёрстку сильнее всего. Граница не превышает сам размер — поэтому при
 * коэффициенте 1 компенсации нет, полотно совпадает с макетом, а подпись 9px на ноутбуке
 * остаётся такой же, как на мониторе 1920, но не мельче.
 */
export function minScreenTextSize(px: number): number {
  return Math.min(px, Math.max(10, 10 + (px - 11) / 2), 12);
}

/**
 * Кегль на полотне, при котором текст размера `px` не опускается ниже своей границы.
 * `scale` — коэффициент полотна; выше единицы компенсации нет, текст растёт вместе с
 * полотном сам.
 */
export function readableTextSize(px: number, scale: number): number {
  const textScale = Math.min(1, scale);
  return Math.min(px * MAX_TEXT_GROWTH, Math.max(px, minScreenTextSize(px) / textScale));
}

/**
 * То же правило значением CSS. Коэффициент берётся из `--text-scale` (`index.css`), и
 * браузер пересчитывает кегль при каждом изменении окна без участия скриптов.
 */
export function readableTextSizeCss(px: number): string {
  const growth = Math.round(px * MAX_TEXT_GROWTH * 100) / 100;
  return `clamp(${px}px, calc(${minScreenTextSize(px)}px / var(--text-scale, 1)), ${growth}px)`;
}

/**
 * Размер или координата, которые раздвигаются вместе с компенсированным текстом: `px` на
 * 1920×1080 и `px + allowance × рост` на ужатом полотне (`--text-growth`, `index.css`).
 * Нужен тесным местам макета, где подписи стоят на фиксированном шаге и подросший текст
 * наезжал бы на соседа.
 */
export function withTextGrowth(px: number, allowance: number): string {
  return `calc(${px}px + ${allowance}px * var(--text-growth, 0))`;
}

/**
 * Верх строки, которая на ужатом полотне растёт вверх, а не вниз: низ строки остаётся на
 * макетной отметке `top + lineHeight`. Так подпись над полем не наезжает на поле, сколько
 * бы ни подрос её кегль. `lineHeight` — высота строки в макете; `1lh` — фактическая.
 */
export function bottomAnchoredTop(top: number, lineHeight: number): string {
  return `calc(${top + lineHeight}px - 1lh)`;
}

/** То же, но строка растёт в обе стороны от своей макетной середины. */
export function centerAnchoredTop(top: number, lineHeight: number): string {
  return `calc(${top + lineHeight / 2}px - 0.5lh)`;
}
